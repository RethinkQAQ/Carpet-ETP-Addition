package com.etpserver.carpetetpaddition.translations;

import com.google.common.reflect.TypeToken;
import com.google.gson.Gson;
import com.google.gson.GsonBuilder;
import org.apache.commons.io.IOUtils;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.util.Collections;
import java.util.Map;

//#if MC >= 12104
//$$ @SuppressWarnings("deprecation")
//#endif
public class CarpetETPAdditionTranslations {
    public static Map<String, String> getTranslationsFromResource(String lang) {
        InputStream langFile = CarpetETPAdditionTranslations.class.getClassLoader().getResourceAsStream("assets/carpetetpaddition/lang/%s.json".formatted(lang));
        if (langFile == null) {
            return Collections.emptyMap();
        }
        String jsonData;
        try {
            jsonData = IOUtils.toString(langFile, StandardCharsets.UTF_8);
        } catch (IOException e) {
            return Collections.emptyMap();
        }
        Gson gson = new GsonBuilder().setLenient().create();
        return gson.fromJson(jsonData, new TypeToken<Map<String, String>>() {}.getType());
    }
}
